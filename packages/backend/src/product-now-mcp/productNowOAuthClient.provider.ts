import type {
  OAuthClientProvider,
  OAuthDiscoveryState,
} from "@modelcontextprotocol/sdk/client/auth.js";
import type {
  OAuthClientInformationMixed,
  OAuthClientMetadata,
  OAuthTokens,
} from "@modelcontextprotocol/sdk/shared/auth.js";
import { ProductNowOAuthSessionStore } from "./productNowOAuthSession.store";

/** Public URLs that identify Towers of Coreborn as an OAuth client. */
export interface ProductNowOAuthClientUrls {
  backendApiUrl: string;
  frontendUrl: string;
}

/**
 * MCP OAuth provider backed by one encrypted browser session.
 */
export class ProductNowOAuthClientProvider implements OAuthClientProvider {
  public authorizationUrl?: URL;
  public readonly clientMetadataUrl: string;
  public readonly redirectUrl: string;
  private readonly frontendUrl: string;

  public constructor(
    private readonly sessionId: string,
    private readonly sessionStore: ProductNowOAuthSessionStore,
    urls: ProductNowOAuthClientUrls,
  ) {
    const normalizedBackendUrl = urls.backendApiUrl.replace(/\/$/, "");
    this.frontendUrl = urls.frontendUrl.replace(/\/$/, "");
    this.clientMetadataUrl = `${normalizedBackendUrl}/.well-known/oauth-client-metadata/towers-of-coreborn.json`;
    this.redirectUrl = `${normalizedBackendUrl}/productnow-mcp/oauth/callback`;
  }

  /**
   * Metadata served by the public CIMD endpoint.
   * @returns OAuth public-client metadata
   */
  public get clientMetadata(): OAuthClientMetadata {
    return {
      client_name: "Towers of Coreborn",
      grant_types: ["authorization_code", "refresh_token"],
      logo_uri: `${this.frontendUrl}/logo.png`,
      redirect_uris: [this.redirectUrl],
      response_types: ["code"],
      token_endpoint_auth_method: "none",
    };
  }

  /**
   * Loads client registration information discovered by the MCP SDK.
   * @returns Client registration information when available
   */
  public async clientInformation(): Promise<
    OAuthClientInformationMixed | undefined
  > {
    return (await this.sessionStore.get(this.sessionId)).clientInformation;
  }

  /**
   * Loads the PKCE verifier for the callback exchange.
   * @returns Stored PKCE verifier
   */
  public async codeVerifier(): Promise<string> {
    const codeVerifier = (await this.sessionStore.get(this.sessionId))
      .codeVerifier;
    if (!codeVerifier) {
      throw new Error("ProductNow OAuth PKCE verifier is missing");
    }
    return codeVerifier;
  }

  /**
   * Loads OAuth discovery data cached for this browser session.
   * @returns Cached discovery data when available
   */
  public async discoveryState(): Promise<OAuthDiscoveryState | undefined> {
    return (await this.sessionStore.get(this.sessionId)).discoveryState;
  }

  /**
   * Captures the authorization URL so the HTTP controller can redirect the browser.
   * @param authorizationUrl - ProductNow authorization URL
   */
  public redirectToAuthorization(authorizationUrl: URL): void {
    this.authorizationUrl = authorizationUrl;
  }

  /**
   * Saves client information selected by CIMD or dynamic registration.
   * @param clientInformation - OAuth client registration data
   */
  public async saveClientInformation(
    clientInformation: OAuthClientInformationMixed,
  ): Promise<void> {
    await this.sessionStore.update(this.sessionId, (session) => ({
      ...session,
      clientInformation,
    }));
  }

  /**
   * Saves the PKCE verifier generated by the MCP SDK.
   * @param codeVerifier - PKCE verifier
   */
  public async saveCodeVerifier(codeVerifier: string): Promise<void> {
    await this.sessionStore.update(this.sessionId, (session) => ({
      ...session,
      codeVerifier,
    }));
  }

  /**
   * Saves OAuth discovery metadata for the callback and future refreshes.
   * @param discoveryState - MCP OAuth discovery result
   */
  public async saveDiscoveryState(
    discoveryState: OAuthDiscoveryState,
  ): Promise<void> {
    await this.sessionStore.update(this.sessionId, (session) => ({
      ...session,
      discoveryState,
    }));
  }

  /**
   * Saves access and refresh tokens after exchange or refresh.
   * @param tokens - ProductNow OAuth tokens
   */
  public async saveTokens(tokens: OAuthTokens): Promise<void> {
    await this.sessionStore.update(this.sessionId, (session) => ({
      ...session,
      tokens,
    }));
  }

  /**
   * Returns the CSRF-bound OAuth state for this browser session.
   * @returns OAuth state value
   */
  public async state(): Promise<string> {
    const oauthState = (await this.sessionStore.get(this.sessionId)).oauthState;
    if (!oauthState) {
      throw new Error("ProductNow OAuth state is missing");
    }
    return oauthState;
  }

  /**
   * Loads ProductNow access and refresh tokens.
   * @returns Stored tokens when connected
   */
  public async tokens(): Promise<OAuthTokens | undefined> {
    return (await this.sessionStore.get(this.sessionId)).tokens;
  }
}
